#!/usr/bin/env python3
"""
SAFAR 2.0 — One-Command Tracker Provisioning Tool (P5-H1 / P2-U1)
Generates CSPRNG pub/sec 64-hex keys, derives 16-hex SHA-256 topic ID,
writes firmware/safar_esp32/secrets.h (including Wi-Fi credentials),
outputs a QR v2 URI & printable label, and appends the device record to git-ignored devices.csv.
"""

import argparse
import csv
import datetime
import hashlib
import os
import secrets
import urllib.parse


def derive_topic_id(pub_hex: str) -> str:
    clean = pub_hex.strip().encode("utf-8")
    return hashlib.sha256(clean).hexdigest()[:16].lower()


def build_qr_v2_uri(
    device_id: str,
    name: str,
    pub_hex: str,
    sec_hex: str,
    sim: str,
    broker_uri: str,
    broker_user: str,
    broker_pass: str,
) -> str:
    params = [
        ("v", "2"),
        ("id", device_id),
        ("name", name),
        ("pub", pub_hex),
        ("sec", sec_hex),
    ]
    if sim:
        params.append(("sim", sim))
    if broker_uri:
        params.append(("broker", broker_uri))
    if broker_user:
        params.append(("bu", broker_user))
    if broker_pass:
        params.append(("bp", broker_pass))
    query = urllib.parse.urlencode(params, quote_via=urllib.parse.quote)
    return f"safar://pair?{query}"


def write_secrets_header(
    out_path: str,
    wifi_ssid: str,
    wifi_pass: str,
    device_id: str,
    name: str,
    sim: str,
    pub_hex: str,
    sec_hex: str,
    broker_host: str,
    broker_port: int,
    broker_user: str,
    broker_pass: str,
) -> None:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    content = f"""#ifndef SAFAR_SECRETS_H
#define SAFAR_SECRETS_H

// Auto-generated by tools/provision.py — DO NOT COMMIT
// 1. WI-FI CREDENTIALS
#ifndef WIFI_SSID
#define WIFI_SSID               "{wifi_ssid}"
#endif
#ifndef WIFI_PASSWORD
#define WIFI_PASSWORD           "{wifi_pass}"
#endif

// 2. TRACKER IDENTITY & ENCRYPTION KEYS
#define SAFAR_DEVICE_ID         "{device_id}"
#define SAFAR_DEVICE_NAME       "{name}"
#define SAFAR_SIM_NUMBER        "{sim}"
#define SAFAR_NOSTR_PUBKEY_HEX  "{pub_hex}"
#define SAFAR_SHARED_SECRET_HEX "{sec_hex}"

// 3. MQTT RELAY BROKER
#define SAFAR_MQTT_HOST         "{broker_host}"
#define SAFAR_MQTT_PORT         {broker_port}
#define SAFAR_MQTT_USER         "{broker_user}"
#define SAFAR_MQTT_PASS         "{broker_pass}"

#endif // SAFAR_SECRETS_H
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)


def main() -> None:
    parser = argparse.ArgumentParser(description="Provision a SAFAR 2.0 hardware tracker")
    parser.add_argument("--id", default="SAFAR_01", help="Tracker ID (e.g. SAFAR_01)")
    parser.add_argument("--name", default="Classic350", help="Motorcycle name")
    parser.add_argument("--sim", default="+919876543210", help="SIM number in E.164 format")
    parser.add_argument("--wifi-ssid", default="YOUR_WIFI_NAME", help="Wi-Fi / Hotspot SSID for ESP32")
    parser.add_argument("--wifi-pass", default="YOUR_WIFI_PASSWORD", help="Wi-Fi / Hotspot Password for ESP32")
    parser.add_argument("--broker", default="ssl://broker.emqx.io:8883", help="MQTT TLS broker URI")
    parser.add_argument("--bu", default="", help="MQTT broker username")
    parser.add_argument("--bp", default="", help="MQTT broker password")
    parser.add_argument("--secrets-out", default="firmware/safar_esp32/secrets.h", help="Path to secrets.h")
    parser.add_argument("--csv-out", default="devices.csv", help="Path to private devices.csv")
    args = parser.parse_args()

    pub_hex = secrets.token_hex(32)
    sec_hex = secrets.token_hex(32)
    topic_id = derive_topic_id(pub_hex)

    qr_uri = build_qr_v2_uri(
        device_id=args.id,
        name=args.name,
        pub_hex=pub_hex,
        sec_hex=sec_hex,
        sim=args.sim,
        broker_uri=args.broker,
        broker_user=args.bu,
        broker_pass=args.bp,
    )

    parsed_broker = urllib.parse.urlparse(args.broker)
    broker_host = parsed_broker.hostname or "broker.emqx.io"
    broker_port = parsed_broker.port or 8883

    write_secrets_header(
        out_path=args.secrets_out,
        wifi_ssid=args.wifi_ssid,
        wifi_pass=args.wifi_pass,
        device_id=args.id,
        name=args.name,
        sim=args.sim,
        pub_hex=pub_hex,
        sec_hex=sec_hex,
        broker_host=broker_host,
        broker_port=broker_port,
        broker_user=args.bu,
        broker_pass=args.bp,
    )

    os.makedirs("tools/out", exist_ok=True)
    label_path = os.path.join("tools/out", f"{args.id}_label.txt")
    with open(label_path, "w", encoding="utf-8") as lf:
        lf.write(f"SAFAR 2.0 TRACKER LABEL\n")
        lf.write(f"ID       : {args.id}\n")
        lf.write(f"Name     : {args.name}\n")
        lf.write(f"Topic ID : {topic_id}\n")
        lf.write(f"QR v2 URI: {qr_uri}\n")

    try:
        import qrcode  # type: ignore
        qr_img = qrcode.make(qr_uri)
        qr_png_path = os.path.join("tools/out", f"{args.id}_qr.png")
        qr_img.save(qr_png_path)
    except ImportError:
        pass

    file_exists = os.path.isfile(args.csv_out)
    with open(args.csv_out, "a", newline="", encoding="utf-8") as cf:
        writer = csv.writer(cf)
        if not file_exists:
            writer.writerow(["timestamp_utc", "device_id", "name", "topic_id", "sim", "broker", "qr_v2_uri"])
        writer.writerow([
            datetime.datetime.now(datetime.timezone.utc).isoformat(),
            args.id,
            args.name,
            topic_id,
            args.sim,
            args.broker,
            qr_uri,
        ])

    print(f"[OK] Provisioned {args.id} ({args.name}) -> topicId={topic_id}")
    print(f"[OK] Wrote {args.secrets_out} and {label_path}")
    print(f"[QR v2] {qr_uri}")


if __name__ == "__main__":
    main()
